// Generates src/lib/mdHeaders.ts from the Metadata Master Sheet header row, with
// each column's Databricks name from metadataFields.json (matched by header text).
// Run with: npx tsx scripts/genMetadataHeaders.ts
import fs from 'node:fs';
import Papa from 'papaparse';
import { colIndex, colLetter, colRange, normHeader } from '../src/lib/excelParse';

const md = Papa.parse<string[]>(fs.readFileSync('data/source/metadata_master.csv', 'utf8')).data;
const meta = JSON.parse(fs.readFileSync('src/data/metadataFields.json', 'utf8')) as Array<{ sourceColumn: string; datalakeColumn: string | null }>;
const norm = (s: string) => normHeader(s).toLowerCase();
const byName = new Map(meta.map((m, i) => [norm(m.sourceColumn), i]));
// Master header -> metadataFields sourceColumn where the wording differs.
const RENAMES: Record<string, string> = {
  CW: 'Forecast Creation Date', CX: 'Forecast - Activation - Low', CY: 'Forecast - Activation - High',
  CZ: 'Bonus Rate - Low', DA: 'Bonus Rate - High', DB: 'Forecast - Avg Spend - Low', DC: 'Forecast - Avg Spend - High',
  DD: 'Forecast - Activation Avg', DE: 'Bonus Rate - Avg', DH: 'Forecast - Bonused Members',
  DP: 'Forecast - Bonus Pts - Low', DQ: 'Forecast - Bonus Pts - High', DR: 'Forecast - Bonus Pts Issued',
  DW: 'Forecast - Redeemable $MDs (100%)', EA: 'Forecast - $MDs (80% or 85%)',
};
const BASICS = ['B', 'D', 'E', 'F', 'G', 'H', 'I', 'J', 'K', 'L', 'M', 'O', 'Q', 'AD', 'AE', 'AF', 'AT', 'AU'];
const letters = [...BASICS, ...colRange('BW', 'FC')];
const out: Record<string, { header: string; metadataFieldIndex: number | null; datalakeColumn: string | null }> = {};
for (const L of letters) {
  const header = normHeader(md[2][colIndex(L)]);
  const key = RENAMES[L] ? norm(RENAMES[L]) : norm(header);
  const idx = byName.has(key) ? byName.get(key)! : null;
  out[L] = { header, metadataFieldIndex: idx, datalakeColumn: idx === null ? null : meta[idx].datalakeColumn };
}
const ts = `// GENERATED by scripts/genMetadataHeaders.ts from data/source/metadata_master.csv.
// Exact Metadata Master Sheet headers (trimmed, whitespace collapsed) and the
// matching metadataFields.json entry (Databricks column). Do not edit by hand.
export const MD_HEADERS: Record<string, { header: string; metadataFieldIndex: number | null; datalakeColumn: string | null }> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync('src/lib/mdHeaders.ts', ts);
const unmatched = letters.filter((L) => out[L].metadataFieldIndex === null && !BASICS.includes(L));
console.log('letters', letters.length, 'unmatched in BW..FC:', unmatched.join(' ') || 'none', '| colLetter check', colLetter(colIndex('FC')));
